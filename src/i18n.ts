export type SupportedLanguage = Language;

export const SUPPORTED_LANGUAGES: { code: SupportedLanguage; label: string; flag: string }[] = [
  { code: 'en', label: 'English', flag: '🇬🇧' },
  { code: 'de', label: 'Deutsch', flag: '🇩🇪' },
  { code: 'fr', label: 'Français', flag: '🇫🇷' },
  { code: 'es', label: 'Español', flag: '🇪🇸' },
  { code: 'it', label: 'Italiano', flag: '🇮🇹' },
  { code: 'pt', label: 'Português', flag: '🇵🇹' },
  { code: 'nl', label: 'Nederlands', flag: '🇳🇱' }
];

let currentLang: SupportedLanguage = 'en';

export function getLanguage(): SupportedLanguage {
  if (typeof window !== 'undefined') {
    try {
      const stored = localStorage.getItem('poli_benchmark_lang');
      if (stored && ['en', 'de', 'fr', 'es', 'it', 'pt', 'nl'].includes(stored)) {
        return stored as SupportedLanguage;
      }
      const navLang = navigator.language.slice(0, 2);
      if (['en', 'de', 'fr', 'es', 'it', 'pt', 'nl'].includes(navLang)) {
        return navLang as SupportedLanguage;
      }
    } catch (e) {
      // Ignore localStorage access errors
    }
  }
  return currentLang;
}

export function setLanguage(lang: SupportedLanguage): void {
  currentLang = lang;
  if (typeof window !== 'undefined') {
    try {
      localStorage.setItem('poli_benchmark_lang', lang);
      document.documentElement.setAttribute('lang', lang);
    } catch (e) {
      // Ignore localStorage access errors
    }
  }
}

export function t(key: string, lang?: SupportedLanguage): string {
  const targetLang = lang || getLanguage();
  const dict = TRANSLATIONS[targetLang] || TRANSLATIONS.en;
  if (dict && dict[key] !== undefined) {
    return dict[key];
  }
  if (TRANSLATIONS.en && TRANSLATIONS.en[key] !== undefined) {
    return TRANSLATIONS.en[key];
  }
  return key;
}

export function applyI18n(lang?: SupportedLanguage): void {
  const targetLang = lang || getLanguage();
  if (typeof document !== 'undefined') {
    document.documentElement.setAttribute('lang', targetLang);
    const elements = document.querySelectorAll('[data-i18n]');
    elements.forEach((el) => {
      const key = el.getAttribute('data-i18n');
      if (key) {
        const text = t(key, targetLang);
        if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
          (el as HTMLInputElement).placeholder = text;
        } else {
          el.textContent = text;
        }
      }
    });
  }
}
